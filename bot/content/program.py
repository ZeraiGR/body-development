"""Учебные недели и темы. Дни не являются стадиями восстановления."""
from __future__ import annotations

# --------------------------------------------------------------------------- #
# Недели (MONTH_1_PLAN)
# --------------------------------------------------------------------------- #
WEEKS: dict[int, dict] = {
    1: {"title": "Знакомство с движением", "focus": "Найти удобную паузу и начать наблюдать за самочувствием."},
    2: {"title": "Знакомые упражнения", "focus": "Попробовать посильные варианты и выбрать удобный момент."},
    3: {"title": "Движение в обычном дне", "focus": "Повторять знакомое и подстраивать объём под переносимость."},
    4: {"title": "Своя короткая практика", "focus": "Оценить записи и выбрать, что продолжить."},
}

# Учебные темы, а не обещания физиологических изменений по календарю.
STAGES: list[tuple[int, int, str, str]] = [
    (1, 7, "Знакомство с движением", "начать можно с короткой посильной паузы"),
    (8, 14, "Знакомые упражнения", "объём и амплитуду подбирают по переносимости"),
    (15, 21, "Движение в обычном дне", "небольшие действия легче повторять в знакомый момент"),
    (22, 30, "Своя короткая практика", "отчёт помогает описать наблюдения, но не ставит диагноз"),
]


def week_for_day(day: int) -> int:
    """День 1..30 -> неделя 1..4 (по MONTH_1_PLAN)."""
    if day <= 7:
        return 1
    if day <= 14:
        return 2
    if day <= 21:
        return 3
    return 4


def stage_for_day(day: int) -> tuple[str, str]:
    """Вернуть (название этапа, научный факт) для дня программы."""
    for lo, hi, name, fact in STAGES:
        if lo <= day <= hi:
            return name, fact
    # За пределами 30 дней — последний этап.
    return STAGES[-1][2], STAGES[-1][3]


def week_actions(week: int) -> dict:
    """Данные недели из MONTH_1_PLAN."""
    return WEEKS[week]
