#!/bin/bash
# spine20-notify.sh — отправляет macOS-нотификацию «правило 20-8».
# Запускается launchd (LaunchAgent com.bodydev.spine20) каждые 20 минут.
#
# Напоминание: встать, 2 вдоха животом, потянуться — снять пиковое давление
# в межпозвоночном диске (~185% при сутулости → ~100% стоя) и запустить помпу губки.
set -euo pipefail

TITLE="🦴 Вставай — губка диска"

# Набор сообщений. Случайное каждый раз — чтобы не приедалось и не стало фоновым шумом.
MESSAGES=(
"Давление в диске сейчас ~185%. Встань — упадёт до 100%. Руки вверх, потянись."
"Губка зажата. Вставание запускает помпу. Два вдоха животом — и сел обратно."
"Восемь секунд: встал → руки вверх → вдох животом → сел. Пик сжатия снят."
"Длительность важнее позы. Прерви монотонное сжатие — встань на 8 секунд."
"Правая сторона каменеет? Встань, потянись, подыши животом — тонус отпустит."
"Сидение — кастрюля на губке. Сними её на 8 секунд: встань и потянись."
"Помпа диска запускается движением, а не покоем. Встань, два глубоких вдоха животом."
"Встань и коснись потолка руками. Восемь секунд — и давление в диске сброшено."
)

# Случайный выбор сообщения (RANDOM корректен в bash).
MSG="${MESSAGES[$((RANDOM % ${#MESSAGES[@]}))]}"

# Нотификация. terminal-notifier даёт лучший UX (кнопка, ignoreDnD), если установлен;
# иначе — встроенный osascript (без зависимостей, работает на macOS 26).
if command -v terminal-notifier >/dev/null 2>&1; then
  terminal-notifier \
    -title "$TITLE" \
    -message "$MSG" \
    -sound Glass \
    -ignoreDnD \
    >/dev/null 2>&1 || true
else
  # Сообщения без двойных кавычек и обратных слэшей — безопасно для AppleScript.
  /usr/bin/osascript <<APPLESCRIPT
display notification "$MSG" with title "$TITLE" sound name "Glass"
APPLESCRIPT
fi
